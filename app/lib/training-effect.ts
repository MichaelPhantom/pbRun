/**
 * Garmin **训练效果（Training Effect，TE）** 的展示口径 —— 卡片与详情页共用的唯一来源。
 *
 * ## 为什么需要这一层
 *
 * 「记录栏目只有跑步」修到第十七层时，剩下的是**字段进库了、三处消费面口径不一**：
 *
 * | 消费面 | 修之前 |
 * |--------|--------|
 * | 详情页概览 | ✅ 「有氧训练效果 0.9」 |
 * | AI 数据块 | ✅ 「训练效果: 0.9」 |
 * | `/list` 卡片 | ❌ 没有 |
 * | 首页「最近活动」卡片 | ❌ 没有 |
 *
 * 而真实库 354 条活动 **354/354 都有 `total_training_effect`**（含全部 120 条
 * 非跑步）。对非跑步活动它更是**唯一的强度量化手段** —— 非跑步提示词明确要求
 * 「改用训练效果（TE）+ 心率区间分布 + 热量量化强度」（`coach-prompts.ts`），
 * 而 19 条非跑步活动（篮球 3 / 乒乓 2 / 羽毛球 1 / HIIT 3 / 室内有氧 9 /
 * 室内骑行 1）在卡片上只有「时长 + 心率 + 徽标」，模型说的 TE 用户在卡片上
 * 找不到出处。
 *
 * ## 三条纪律
 *
 * 1. **`TE = 0` 是有效值，不是缺失**。真实库羽毛球 `560273729` 精确为 0、
 *    跳绳 3 条为 0–0.1。判空必须 `!= null` —— 用真值判断（`if (te)`）会把
 *    这几条唯一能说明「这课基本没有训练刺激」的活动静默吞掉。
 * 2. **不做运动类型门控**。`training_load` 只有跑步三类型 + 力量训练产出
 *    （`producesTrainingLoad`），TE 则是设备对**所有类型**都写（354/354）。
 *    若在展示层写一份「哪些类型有 TE」的白名单，就又是第三份类型判断。
 * 3. **数值与标签一起消失**。没有 TE 时调用方整项不渲染（连「训练效果」三个字），
 *    与 `docs/features.md` §「活动数据块的『缺失』分两类」一致 —— 这里是
 *    「该活动没测到」，但 TE 在真实库从未缺过，卡片上没有它就说明数据异常，
 *    显示 `--` 只会多一个噪音格。
 */

/**
 * 卡片上的标签。
 *
 * 详情页写「**有氧**训练效果」是因为它紧挨着「无氧训练效果」，不写「有氧」
 * 会让用户以为那一格是两者的合计。卡片只展示有氧 TE（非跑步唯一的强度
 * 量化手段就是它），没有歧义，故用短标签 —— 与 AI 数据块非跑步分支的
 * 「训练效果: 0.9」同一措辞。
 */
export const TRAINING_EFFECT_LABEL = '训练效果';

/**
 * 详情页概览的标签。
 *
 * 详情页同时展示有氧与无氧两格，标签必须写「有氧」把两者区分开；卡片只展示
 * 有氧 TE，故用短标签（见上）。
 */
export const TRAINING_EFFECT_DETAIL_LABEL = '有氧训练效果';

/**
 * 格式化 TE（保留一位小数，与详情页 / AI 数据块一致）。
 *
 * `null` / `undefined` → `null`（调用方据此整项不渲染）。
 * **`0` → `'0.0'`**（有效值，见文件头纪律 1）。
 */
export function formatTrainingEffect(te: number | null | undefined): string | null {
  if (te == null || !Number.isFinite(te)) return null;
  return te.toFixed(1);
}
