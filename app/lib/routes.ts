/**
 * 站内路由的**唯一来源** —— 尤其「活动详情页」的 URL 形态。
 *
 * ## 为什么需要这一层
 *
 * 详情页的路由文件是 `app/pages/[id]/page.tsx`，所以 URL 是 `/pages/{id}`。
 * 这个事实**只存在于文件系统里** —— 任何写 `href` 的地方都不会被类型系统检查，
 * 写错也只会在用户点击时变成 404。
 *
 * 第二十八类缺陷（2026-11-08）就是这么发生的：`/insight` 的常跑路线卡两处
 * 活动链接写成 `/${activityId}`（少了 `/pages` 段）。
 *
 * | 位置 | 错误写法 | 生产实测 |
 * |------|----------|----------|
 * | 「最佳」徽章 | `href={`/${r.best.activityId}`}` | `/pbrun/659795962` → **404** |
 * | 「最近 5 次」配速 | `href={`/${x.activityId}`}` | `/pbrun/pages/659795962` → 200 |
 *
 * 近 90 天的洞察页有 **24 个**这样的死链（6 条路线 × (1 最佳 + ≤5 最近)）。
 * 用户点「最佳 5:14/km」想看是哪一次跑，得到的是 404 页 —— 数据在库里、
 * 计算也正确，只是**链接指错了地方**。
 *
 * ## 为什么测试拦不住
 *
 * 组件测试的夹具里 `best: null, recent: []` —— 恰好把两条分支永久跳过。
 * 分支永远不执行，写错的路由也就永远不显形。这与「按函数写死的守卫看不见
 * 另一个消费面」同源：**夹具的默认值把分支藏了**。
 *
 * ## 纪律
 *
 * 所有指向活动详情页的链接/跳转都必须走 `activityDetailPath()`。
 * 静态守卫见 `tests/unit/ci/route-hygiene.test.ts`：它扫 `app/**` 里
 * `href={`/` 后紧跟插值的形态，任何**不含** `/pages/` 的动态根路径即报错。
 */

/** 活动详情页的路径（`app/pages/[id]/page.tsx`）。 */
export function activityDetailPath(activityId: number | string): string {
  return `/pages/${activityId}`;
}
