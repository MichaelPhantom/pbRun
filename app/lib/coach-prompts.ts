/** 各统计界面的「分析任务」提示句（拼在 user 消息末尾，与 system 的职责呼应）。 */
export function statisticsTaskLine(surface: StatisticsSurface, rangeLabel: string): string {
  const where = `数据区间：${rangeLabel}`;
  switch (surface) {
    case 'dashboard':
      return `请给出**当前状态快照**与**本周训练安排**（${where}）。不要写多月规划。`;
    case 'analysis':
      return `请诊断本区间的**强度结构与负荷状态**，并给出下一阶段的区间配比建议（${where}）。`;
    case 'stats':
      return `请解读本周期（${where}）的**总量与纪录**，并指出读者最容易误读的数据口径。`;
    case 'insight':
    default:
      return `请基于以上【跑者画像】与【全局训练指标】（${where}），进行一次世界顶级教练水准的综合诊断与长期辅导，覆盖能力演进、训练结构、多维洞察、优势短板与未来规划。`;
  }
}
