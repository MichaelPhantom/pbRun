/** 构造某个统计界面的 system prompt（各界面互不相同，共享角色与边界）。 */
export function statisticsSystemPrompt(surface: StatisticsSurface): string {
  const spec = STATISTICS_SURFACES_SPEC[surface];
  return `${STATISTICS_ROLE}

【本界面职责 · ${spec.label}】
${spec.duty}

【输出格式】
${spec.format}

【写作纪律】
- 篇幅：${spec.limit}
- 先引用数据再下结论，避免空话套话。
- 结合【跑者画像】因材施教；语气客观、专业、鼓励。
- 若某个数据块为空（例如没有气温样本、没有功率数据），直接跳过，不要写「数据缺失」。`;
}

