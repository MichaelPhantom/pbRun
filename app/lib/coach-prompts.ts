/**
 * AI 教练的**提示词单一来源** —— 按「能力维度 × 界面」分档。
 *
 * ## 为什么必须分档
 *
 * 2026-10-29 审计发现：同一套 `GLOBAL_COACH_PROMPT` 被**四个页面**共用
 * （首页 / 洞察 / 分析 / 统计），而它同时要求「训练结构评估」和「未来 2-4 周
 * 处方 + 3 个月目标」；单次活动分析的两套 prompt 也各自带「3 个月发展目标 /
 * 3 个月建议」。于是**两个能力维度互相污染**：
 *
 * | 界面 | 手上的数据 | 却被告知要输出 |
 * |------|-----------|----------------|
 * | 统计页（周/月/年） | 只有一个自然周期的总量与纪录 | 「2-4 周处方 + 3 个月目标」 |
 * | 首页（本月概览） | 本月跑量/CTL/近期活动 | 同上（全历史 + 三个月规划） |
 * | 单次活动（一次跑） | 一次跑的分段/配速/心率 | 「3 个月目标」「长期发展方向」 |
 *
 * 后果不是「答得不好」，而是**模型被迫在缺少依据时编造**：一次跑的明细里没有
 * 跨月结构，却要它给出 3 个月目标；一个月的总量里没有单次分段，却要它诊断
 * 「本次配速策略」。两个界面因此会给出同一类内容，用户也无法判断该问谁。
 *
 * ## 分档规则
 *
 * ```
 * 能力维度 (capability)                 界面 (surface)
 * ├── single-activity  单次训练          activity（活动详情页）
 * └── statistics       区间聚合          dashboard（首页·最近状态）
 *                                       insight（汇总页·区间诊断）
 *                                       analysis（分析页·强度与负荷）
 *                                       stats（统计页·自然周期总量）
 * ```
 *
 * - **单次活动**：只对这一次训练负责 —— 执行质量、当次强度与代价、横向定位、
 *   下一次怎么练。**不做**周期化与多月规划（数据里没有跨月结构）。
 * - **统计类**：只对所选区间负责 —— 趋势/结构/负荷/周期化/横向对比。
 *   **不做**单次技术动作与分段诊断（数据里没有分段明细），被问到时指向活动详情页。
 *
 * 每个 surface 的提示词都显式写出「本界面职责」与「输出格式」，并共享同一段
 * 能力边界（`CAPABILITY_BOUNDARY`），因此任意两份提示词都**不可能完全相同**，
 * 且都声明了自己**不能**回答什么、该指向谁。
 */

/** 能力维度：单次活动 vs 统计类。两者数据与结论的单位都不同，不可混用。 */
export type CoachCapability = 'single-activity' | 'statistics';

/** AI 教练的挂载界面（每个界面一套提示词）。 */
export type CoachSurface = 'activity' | 'dashboard' | 'insight' | 'analysis' | 'stats';

/** 统计类界面（`activity` 之外的全部）。 */
export type StatisticsSurface = Exclude<CoachSurface, 'activity'>;

const STATISTICS_SURFACES: StatisticsSurface[] = ['dashboard', 'insight', 'analysis', 'stats'];

/** 运行时校验：请求体里的 `surface` 只能是白名单值（防止任意字符串注入提示词）。 */
export function isStatisticsSurface(v: unknown): v is StatisticsSurface {
  return typeof v === 'string' && (STATISTICS_SURFACES as string[]).includes(v);
}

/**
 * 两个能力维度的**职责边界**（各自声明「我不回答什么、该找谁」）。
 *
 * 这一段是分档的核心：没有它，模型在遇到越界问题时会硬答（编造），
 * 而不是把用户导到有数据的那一侧。
 */
export const CAPABILITY_BOUNDARY: Record<CoachCapability, string> = {
  'single-activity': `【职责边界 —— 本次分析只覆盖这一次训练】
- 你负责：本次的执行质量、当次强度与生理代价、与可比样本的横向定位、以及**下一次**怎么练。
- 你不负责：跨多次活动的统计与周期化（月跑量、周均、趋势排名、阶段划分、赛季规划）。
  数据里没有跨月结构，任何「3 个月目标」「赛季安排」「长期发展方向」都是编造 —— 不要写。
- 若用户追问越界问题：明确说明「这属于汇总页/洞察页教练的范围」，再用本次数据回答
  其中与本次有关的那一部分（例如「本次在这次训练里的位置」），**绝不编造区间统计**。`,
  statistics: `【职责边界 —— 本次只覆盖所选区间的聚合数据】
- 你负责：区间内的趋势、训练结构、负荷管理（CTL/ATL/TSB、ACWR）、周期化、类别/气温/路线对比。
- 你不负责：某一次训练的分段执行、步频步幅细节、某一段的心率漂移、触地时间等技术动作。
  这些只有活动详情页的 AI 分析才有数据。
- 若用户追问越界问题：明确说明「这需要打开那次活动的详情页分析」，再给出你能从聚合数据
  回答的相关部分（例如「那类训练在本区间的整体表现」），**绝不编造单次明细**。`,
};

